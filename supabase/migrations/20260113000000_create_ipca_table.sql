-- Tabela para armazenar índices de IPCA (Índice de Preços ao Consumidor Amplo)
create table public.ipca (
  id bigint generated by default as identity primary key,
  ano integer not null unique,
  percentual numeric(5,2) not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_by uuid references auth.users(id)
);

-- Enable RLS
alter table public.ipca enable row level security;

-- Policies
-- Público pode ler IPCA
create policy "Público pode ler IPCA" on public.ipca
  for select using (true);

-- Apenas admins podem criar/editar/deletar IPCA
create policy "Admins podem gerenciar IPCA" on public.ipca
  for all using (
    public.is_admin(auth.uid())
  );

-- Index para busca por ano
create index idx_ipca_ano on public.ipca(ano);

-- Trigger para atualizar updated_at
create trigger update_ipca_updated_at
  before update on public.ipca
  for each row
  execute function update_updated_at_column();
